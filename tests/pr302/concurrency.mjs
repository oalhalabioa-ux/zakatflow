// Only a disposable local Supabase stack is allowed. No hosted keys or URLs.
import { strict as assert } from 'node:assert';
import { randomUUID, randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';

const api = process.env.API_URL;
const anon = process.env.ANON_KEY;
const service = process.env.SERVICE_ROLE_KEY;
const report = process.env.PR302_REPORT_DIR;
if (api !== 'http://127.0.0.1:54321' || !anon || !service || !report) {
  throw new Error('Expected the disposable local Supabase API and local keys');
}
const admin = createClient(api, service, {auth:{persistSession:false,autoRefreshToken:false}});
const sql = (query) => {
  const r = spawnSync('psql', ['postgresql://postgres:postgres@127.0.0.1:54322/postgres', '-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-c', query], {encoding:'utf8'});
  if (r.status !== 0) throw new Error(`Local SQL fixture or assertion failed: ${r.stderr}`);
  return r.stdout.trim();
};
const rpc = async (client, name, args) => {
  const {data,error} = await client.rpc(name,args);
  if (error) throw new Error(`${name}: ${error.code || 'ERROR'} ${error.message}`);
  return data;
};
const makeUser = async (n) => {
  const email = `pr302-${n}-${randomUUID()}@example.invalid`;
  const password = randomBytes(32).toString('hex');
  const {data,error} = await admin.auth.admin.createUser({email,password,email_confirm:true});
  if (error || !data.user) throw new Error(`Local Auth createUser failed: ${error?.message}`);
  const client = createClient(api, anon, {auth:{persistSession:false,autoRefreshToken:false}});
  const login = await client.auth.signInWithPassword({email,password});
  if (login.error || !login.data.session) throw new Error(`Local Auth sign-in failed: ${login.error?.message}`);
  return {id:data.user.id,client};
};

async function main() {
  mkdirSync(report,{recursive:true});
  const [first,second] = await Promise.all([makeUser(1),makeUser(2)]);
  assert.notEqual(first.id,second.id);
  const org = randomUUID(), party = randomUUID();
  // UUID values are generated by Node, not external input.
  sql(`insert into public.organizations(id,owner_user_id,name,base_currency,entity_type,status) values ('${org}','${first.id}','PR302 disposable company','SAR','FAMILY','ACTIVE');
       insert into public.organization_members(organization_id,user_id,role,status) values ('${org}','${first.id}','OWNER','ACTIVE'),('${org}','${second.id}','OWNER','ACTIVE') on conflict(organization_id,user_id) do update set role='OWNER',status='ACTIVE';
       insert into public.liquidity_counterparties(id,organization_id,name,party_type,created_by) values ('${party}','${org}','PR302 synthetic counterparty','OTHER','${first.id}');`);
  const date = new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Riyadh',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
  const opened = await rpc(first.client,'open_financial_account',{p_payload:{request_id:randomUUID(),scope:'ORGANIZATION',organization_id:org,type:'BANK',name:'PR302 disposable cash',currency:'SAR',opening_balance:1000,opening_date:date,fx_rate:1}});
  const bank = opened.id;
  assert.match(bank,/^[0-9a-f-]{36}$/i);
  const payload = (n) => ({organization_id:org,request_id:randomUUID(),kind:'LOAN',mode:'NEW',side:'PAYABLE',counterparty_id:party,entity_id:null,account_id:bank,category:'O_AP_LOAN',description:`PR302 simultaneous first posting ${n}`,reference:`PR302-${n}`,date,currency:'SAR',exchange_rate:1,principal:100,schedule:[{amount:100,due_date:date}]});
  // Independent JWT sessions issue different operations concurrently.
  const created = await Promise.all([rpc(first.client,'create_debt_contract',{p_payload:payload(1)}),rpc(second.client,'create_debt_contract',{p_payload:payload(2)})]);
  assert.notEqual(created[0].id,created[1].id);
  assert.notEqual(created[0].eventId,created[1].eventId);
  // Cross-approval satisfies independent-approval policies when configured.
  await Promise.all([rpc(second.client,'approve_financial_event',{p_event_id:created[0].eventId,p_note:'PR302 synthetic approval'}),rpc(first.client,'approve_financial_event',{p_event_id:created[1].eventId,p_note:'PR302 synthetic approval'})]);
  const posted = await Promise.all([rpc(first.client,'post_debt_contract',{p_id:created[0].id}),rpc(second.client,'post_debt_contract',{p_id:created[1].id})]);
  assert.ok(posted.every(x => x.status === 'ACTUAL'));
  const ids = created.map(x => x.id);
  const events = created.map(x => x.eventId);
  const stats = JSON.parse(sql(`select json_build_object(
    'balance',(select current_balance from public.liquidity_accounts where id='${bank}'),
    'vouchers',(select count(*) from public.voucher_numbers where source_table='debt_contracts' and source_id in ('${ids[0]}','${ids[1]}')),
    'distinct_numbers',(select count(distinct document_number) from public.voucher_numbers where source_table='debt_contracts' and source_id in ('${ids[0]}','${ids[1]}')),
    'consecutive',(select max(sequence)-min(sequence) from public.voucher_numbers where source_table='debt_contracts' and source_id in ('${ids[0]}','${ids[1]}')),
    'loan_prefix_count',(select count(*) from public.voucher_numbers where source_table='debt_contracts' and source_id in ('${ids[0]}','${ids[1]}') and prefix='LR' and issue_year=extract(year from now() at time zone 'Asia/Riyadh')),
    'settlements',(select count(*) from public.liquidity_settlements where financial_event_id in ('${events[0]}','${events[1]}') and status='POSTED'),
    'settlement_sum',(select coalesce(sum(base_amount),0) from public.liquidity_settlements where financial_event_id in ('${events[0]}','${events[1]}') and status='POSTED'),
    'event_count',(select count(*) from public.financial_events where id in ('${events[0]}','${events[1]}') and status='ACTUAL'),
    'line_count',(select count(*) from public.financial_event_lines where event_id in ('${events[0]}','${events[1]}')),
    'line_sum',(select coalesce(sum(base_amount),0) from public.financial_event_lines where event_id in ('${events[0]}','${events[1]}')),
    'obligation_sum',(select coalesce(sum(settleable_base_amount),0) from public.financial_event_obligations where event_id in ('${events[0]}','${events[1]}')),
    'commands',(select count(*) from public.financial_event_command_registry where financial_event_id in ('${events[0]}','${events[1]}') and command_type='DEBT_CONTRACT_POST'))::text`));
  assert.equal(Number(stats.balance),1200);
  assert.equal(Number(stats.vouchers),2);
  assert.equal(Number(stats.distinct_numbers),2);
  assert.equal(Number(stats.consecutive),1);
  assert.equal(Number(stats.loan_prefix_count),2);
  assert.equal(Number(stats.settlements),2);
  assert.equal(Number(stats.settlement_sum),200);
  assert.equal(Number(stats.event_count),2);
  assert.equal(Number(stats.line_count),2);
  assert.equal(Number(stats.line_sum),200);
  assert.equal(Number(stats.obligation_sum),200);
  assert.equal(Number(stats.commands),2);
  writeFileSync(`${report}/concurrency.json`,JSON.stringify({test:'two-users-first-debt-funding',status:'PASS',...stats},null,2));
}
main().catch(error => {
  if (report) { mkdirSync(report,{recursive:true}); writeFileSync(`${report}/concurrency.json`,JSON.stringify({test:'two-users-first-debt-funding',status:'FAIL',error:String(error.message)},null,2)); }
  console.error('PR302 local concurrency test failed:',error.message);
  process.exitCode=1;
});
